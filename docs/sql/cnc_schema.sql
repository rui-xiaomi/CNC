  SEND_TIME       DATETIME    NOT NULL COMMENT '下发时间',
  FINISH_TIME     DATETIME    NULL COMMENT '完成时间',
  ERROR_MSG       VARCHAR(500) NULL COMMENT '失败原因',
  AUTHOR          VARCHAR(15) NULL,
