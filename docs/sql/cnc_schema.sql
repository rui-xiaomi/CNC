  KEY idx_rec_eq (EQUIMENT_ID),
  KEY idx_rec_electrode (ELECTRODE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='加工/检测记录';

-- 12. AGV 任务记录
CREATE TABLE MAS_AUTO_AGV_TASK (
