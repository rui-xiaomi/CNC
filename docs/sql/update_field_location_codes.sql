UPDATE MAS_AUTO_LOCATION_MAP
SET RCS_CODE='201102'
WHERE LOC_TYPE='POSITION' AND EQUIMENT_ID=1 AND POSITION_ID=2 AND STATE='0';

-- FRAME cell 备注名扣成 L层P位（可重复）
UPDATE MAS_AUTO_LOCATION_MAP m
JOIN MAS_AUTO_FRAME f ON f.ID1 = m.FRAME_ID AND f.STATE = '0'
SET m.LOC_NAME = CONCAT(
  'L', CAST(SUBSTRING(m.RCS_CODE, CHAR_LENGTH(f.FRAME_CODE) + 1,
        CHAR_LENGTH(m.RCS_CODE) - CHAR_LENGTH(f.FRAME_CODE) - 2) AS UNSIGNED),
  'P', CAST(RIGHT(m.RCS_CODE, 2) AS UNSIGNED))
WHERE m.STATE = '0' AND m.LOC_TYPE = 'FRAME' AND m.RCS_TYPE = 'cell'
  AND m.RCS_CODE LIKE CONCAT(f.FRAME_CODE, '%')
  AND CHAR_LENGTH(m.RCS_CODE) >= CHAR_LENGTH(f.FRAME_CODE) + 3;

SELECT ID1, FRAME_NAME, FRAME_CODE, LAYER_TOTAL, SLOTS_PER_LAYER, SLOT_TOTAL
FROM MAS_AUTO_FRAME WHERE STATE='0' ORDER BY ID1;

SELECT FRAME_ID, COUNT(*) slots, SUM(SLOT_STATE='1') occupied
FROM MAS_AUTO_FRAME_SLOT GROUP BY FRAME_ID ORDER BY FRAME_ID;

SELECT FRAME_ID, RCS_TYPE, COUNT(*) c
FROM MAS_AUTO_LOCATION_MAP
WHERE STATE='0' AND LOC_TYPE='FRAME'
GROUP BY FRAME_ID, RCS_TYPE
ORDER BY FRAME_ID, RCS_TYPE;
