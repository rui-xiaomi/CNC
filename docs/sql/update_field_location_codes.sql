-- 料架布局：10 层 × 左右 2 位。
-- cell = 货架码 + 层号（不补零）+ 层内位 2 位：
--   上料 101：L1=101101/101102 … L10=1011001/1011002
--   中转 301/302、下料 303、NG 401：同规则
-- 会重建全部料架槽位（含预记）。可重复执行。禁止在生产库未备份时执行。执行后须重启客户端。

USE cnc_auto;

