UPDATE MAS_AUTO_FRAME SET FRAME_NAME='NG架401', FRAME_CODE='401', FRAME_IDENTIFY_CODE='401',
  LAYER_TOTAL=10, SLOTS_PER_LAYER=2, SLOT_TOTAL=20 WHERE ID1=91;
UPDATE MAS_AUTO_FRAME SET FRAME_NAME='中转架302', FRAME_CODE='302', FRAME_IDENTIFY_CODE='302',
  LAYER_TOTAL=10, SLOTS_PER_LAYER=2, SLOT_TOTAL=20 WHERE ID1=92;

UPDATE MAS_AUTO_LOCATION_MAP SET STATE='1'
WHERE STATE='0' AND (
  (LOC_TYPE='AREA' AND LOC_NAME IN ('LOAD_AREA', 'UNLOAD_AREA'))
  OR RCS_CODE IN ('651001','651002','651003','651091','651092','653002','653091','653092')
);

-- 作废旧 cell（2×5 / 2×6 多出的位，如 101103、301106）
UPDATE MAS_AUTO_LOCATION_MAP m
LEFT JOIN (
  SELECT CONCAT(f.code, l.n, LPAD(p.n, 2, '0')) AS code
  FROM (
    SELECT '101' AS code UNION ALL SELECT '301' UNION ALL SELECT '302'
    UNION ALL SELECT '303' UNION ALL SELECT '401'
  ) f
  CROSS JOIN (
    SELECT 1 n UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5
    UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9 UNION ALL SELECT 10
  ) l
  CROSS JOIN (SELECT 1 n UNION ALL SELECT 2) p
) keep ON keep.code = m.RCS_CODE
SET m.STATE='1'
WHERE m.STATE='0' AND m.LOC_TYPE='FRAME' AND m.RCS_TYPE='cell'
  AND m.FRAME_ID IN (1, 2, 3, 91, 92)
  AND keep.code IS NULL;

-- 同一 RCS_CODE 多条活动：留最小 ID1
UPDATE MAS_AUTO_LOCATION_MAP m
JOIN (
  SELECT RCS_CODE, MIN(ID1) AS keep_id
  FROM MAS_AUTO_LOCATION_MAP
  WHERE STATE='0'
  GROUP BY RCS_CODE
  HAVING COUNT(*) > 1
) d ON d.RCS_CODE = m.RCS_CODE
SET m.STATE='1'
WHERE m.STATE='0' AND m.ID1 <> d.keep_id;

DELETE FROM MAS_AUTO_FRAME_SLOT WHERE FRAME_ID IN (1, 2, 3, 91, 92);

INSERT INTO MAS_AUTO_FRAME_SLOT
  (FRAME_ID, SLOT_NO, LAYER_NO, POS_IN_LAYER, SLOT_STATE, ELECTRODE_ID, BIND_SOURCE, BIND_TIME)
SELECT
  f.id,
  (l.n - 1) * 2 + p.n,
  l.n,
  p.n,
  CASE WHEN f.id = 1 THEN '1' ELSE '0' END,
  CASE WHEN f.id = 1 THEN CONCAT('101', l.n, LPAD(p.n, 2, '0')) ELSE NULL END,
  CASE WHEN f.id = 1 THEN 'MANUAL' ELSE NULL END,
  CASE WHEN f.id = 1 THEN NOW() ELSE NULL END
FROM (SELECT 1 AS id UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 91 UNION ALL SELECT 92) f
CROSS JOIN (
  SELECT 1 n UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5
  UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9 UNION ALL SELECT 10
) l
CROSS JOIN (SELECT 1 n UNION ALL SELECT 2) p;

INSERT INTO MAS_AUTO_LOCATION_MAP (LOC_TYPE, FRAME_ID, LOC_NAME, RCS_CODE, RCS_TYPE, STATE, AUTHOR)
SELECT v.LOC_TYPE, v.FRAME_ID, v.LOC_NAME, v.RCS_CODE, v.RCS_TYPE, '0', 'system'
FROM (
  SELECT 'FRAME' LOC_TYPE, 1 FRAME_ID, '上料架101' LOC_NAME, '101' RCS_CODE, 'shelf' RCS_TYPE
  UNION ALL SELECT 'FRAME', 2,  '中转架301', '301', 'shelf'
  UNION ALL SELECT 'FRAME', 3,  '下料总架303', '303', 'shelf'
  UNION ALL SELECT 'FRAME', 91, 'NG架401',  '401', 'shelf'
  UNION ALL SELECT 'FRAME', 92, '中转架302', '302', 'shelf'
) v
WHERE NOT EXISTS (
  SELECT 1 FROM MAS_AUTO_LOCATION_MAP m
  WHERE m.RCS_CODE = v.RCS_CODE AND m.STATE = '0'
);

INSERT INTO MAS_AUTO_LOCATION_MAP (LOC_TYPE, FRAME_ID, LOC_NAME, RCS_CODE, RCS_TYPE, STATE, AUTHOR)
SELECT 'FRAME', f.id, CONCAT('L', l.n, 'P', p.n), CONCAT(f.code, l.n, LPAD(p.n, 2, '0')), 'cell', '0', 'system'
FROM (
  SELECT 1 AS id, '101' AS code
  UNION ALL SELECT 2, '301'
  UNION ALL SELECT 3, '303'
  UNION ALL SELECT 91, '401'
  UNION ALL SELECT 92, '302'
) f
CROSS JOIN (
  SELECT 1 n UNION ALL SELECT 2 UNION ALL SELECT 3 UNION ALL SELECT 4 UNION ALL SELECT 5
  UNION ALL SELECT 6 UNION ALL SELECT 7 UNION ALL SELECT 8 UNION ALL SELECT 9 UNION ALL SELECT 10
) l
CROSS JOIN (SELECT 1 n UNION ALL SELECT 2) p
WHERE NOT EXISTS (
  SELECT 1 FROM MAS_AUTO_LOCATION_MAP m
  WHERE m.RCS_CODE = CONCAT(f.code, l.n, LPAD(p.n, 2, '0')) AND m.STATE = '0'
);

UPDATE MAS_AUTO_LOCATION_MAP
